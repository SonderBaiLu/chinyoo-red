// --- Helpers: Polylang string translation with safe fallback -------------------
function ew__( $s ) {
	return function_exists( 'pll__' ) ? pll__( $s ) : $s;
}
function ew_e( $s ) {
	echo function_exists( 'pll__' ) ? pll__( $s ) : $s; // raw; caller must escape
}
function ew_esc_html__( $s ) {
	return function_exists( 'pll__' ) ? pll_esc_html__( $s ) : esc_html( $s );
}
function ew_esc_html_e( $s ) {
	echo function_exists( 'pll__' ) ? pll_esc_html__( $s ) : esc_html( $s );
}
function ew_esc_attr__( $s ) {
	return function_exists( 'pll__' ) ? pll_esc_attr__( $s ) : esc_attr( $s );
}
function ew_esc_attr_e( $s ) {
	echo function_exists( 'pll__' ) ? pll_esc_attr__( $s ) : esc_attr( $s );
}

/**
 * Plural-aware helper (Polylang strings have no plural form support).
 * Picks singular/plural source by count, then translates the picked string.
 */
function ew_n( $single, $plural, $n ) {
	$s = ( 1 == $n ) ? $single : $plural;
	return function_exists( 'pll__' ) ? pll__( $s ) : $s;
}

